"""Package the ``agentlab`` sources into a script so lesson cells can ``import agentlab`` in Pyodide."""

import json
from pathlib import Path

RUNTIME_SCRIPT = Path("assets") / "js" / "agentlab-src.js"
HEADER = "/* Generated by `pixi run sync-runtime` from src/agentlab/. Do not edit by hand. */\n"


def collect_sources(package_dir: Path) -> dict[str, str]:
    """Read every Python file of a package, keyed by its path inside ``site-packages``.

    Args:
        package_dir: The package directory, such as ``src/agentlab``.

    Returns:
        Sources keyed by paths like ``agentlab/mock.py``, sorted for stable output.
    """
    base = package_dir.parent
    return {
        path.relative_to(base).as_posix(): path.read_text(encoding="utf-8")
        for path in sorted(package_dir.rglob("*.py"))
        if "__pycache__" not in path.parts
    }


def render_runtime(sources: dict[str, str]) -> str:
    """Render the sources as a script that defines ``window.PP_PY_MODULES``.

    Args:
        sources: Module sources keyed by their ``site-packages`` path.

    Returns:
        The script text.
    """
    payload = json.dumps(sources, indent=1, sort_keys=True, ensure_ascii=False).replace("</", "<\\/")
    return f"{HEADER}window.PP_PY_MODULES = {payload};\n"


def runtime_path(root: Path) -> Path:
    """Return where the generated script lives.

    Args:
        root: Repository root.

    Returns:
        ``docs/assets/js/agentlab-src.js`` under ``root``.
    """
    return root / "docs" / RUNTIME_SCRIPT


def write_runtime(root: Path) -> Path:
    """Regenerate the runtime script from ``src/agentlab``.

    Args:
        root: Repository root.

    Returns:
        The path written.
    """
    target = runtime_path(root)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_runtime(collect_sources(root / "src" / "agentlab")), encoding="utf-8")
    return target


def runtime_is_current(root: Path) -> bool:
    """Tell whether the committed runtime script matches ``src/agentlab``.

    Args:
        root: Repository root.

    Returns:
        ``True`` when regenerating would change nothing.
    """
    target = runtime_path(root)
    expected = render_runtime(collect_sources(root / "src" / "agentlab"))
    return target.is_file() and target.read_text(encoding="utf-8") == expected
